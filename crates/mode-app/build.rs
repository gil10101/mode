use std::path::Path;

/// `bundle.externalBin` in tauri.conf.json (the relay sidecar).
const SIDECAR: &str = "binaries/mode-hook";

/// tauri-build copies every `bundle.externalBin` entry,
/// `binaries/mode-hook-<target triple>[.exe]`, next to the build output and
/// fails the build when that file is missing. `ui/scripts/build-hook.mjs`
/// creates it (`npm run tauri -- dev | build` runs it first); a plain
/// `cargo build` / `cargo test` of the workspace does not, so without the
/// file the entry is dropped for this compile through tauri-build's
/// `TAURI_CONFIG` merge patch (`null` removes a key). The app then finds the
/// relay cargo built next to its binary (`target/<profile>/mode-hook`), and
/// the bundler, which reads tauri.conf.json itself, still requires the file.
/// No placeholder is ever written, so none can reach a bundle or replace the
/// dev relay in `target/<profile>/`.
fn drop_missing_sidecar() {
    // A directory is scanned recursively: the script reruns when the sidecar
    // appears, changes or goes away. It must exist, or cargo would rerun the
    // script (and rebuild the crate) on every build.
    let _ = std::fs::create_dir_all("binaries");
    println!("cargo:rerun-if-changed=binaries");
    let target = std::env::var("TARGET").unwrap_or_default();
    let ext = if target.contains("windows") {
        ".exe"
    } else {
        ""
    };
    let file = format!("{SIDECAR}-{target}{ext}");
    if Path::new(&file).is_file() {
        return;
    }
    let mut patch: serde_json::Value = std::env::var("TAURI_CONFIG")
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .filter(serde_json::Value::is_object)
        .unwrap_or_else(|| serde_json::json!({}));
    let bundle = patch
        .as_object_mut()
        .expect("an object")
        .entry("bundle")
        .or_insert_with(|| serde_json::json!({}));
    if !bundle.is_object() {
        *bundle = serde_json::json!({});
    }
    bundle
        .as_object_mut()
        .expect("an object")
        .insert("externalBin".into(), serde_json::Value::Null);
    // SAFETY: the build script is single-threaded here; tauri-build reads
    // the variable below in this same process.
    unsafe { std::env::set_var("TAURI_CONFIG", patch.to_string()) };
    if std::env::var("PROFILE").as_deref() == Ok("release") {
        println!(
            "cargo:warning={file} is missing: this build carries no relay sidecar \
             (run `node ui/scripts/build-hook.mjs` or `npm run tauri -- build`)"
        );
    }
}

